def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", required=True)
    parser.add_argument("--policy", choices=tuple(POLICIES), required=True)
    parser.add_argument("--alpha", type=float, required=True)
    parser.add_argument("--budget", type=int, default=650)
    parser.add_argument(
        "--initial-path-file",
        default="inputs/common_initial_path_equidistant.npz",
    )
    parser.add_argument("--study-label", default="ala_v10")
    parser.add_argument("--print-command", action="store_true")
    args = parser.parse_args()

    root = Path(args.root).expanduser().resolve()
    if args.budget < 2:
        raise ValueError("budget must allow an initial and a trial evaluation")
    if not args.study_label or any(
        character not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-"
        for character in args.study_label
    ):
        raise ValueError("study-label must contain only letters, digits, '_' or '-'")
    invocation = command(
        root,
        args.policy,
        args.alpha,
        args.budget,
        initial_path_file=args.initial_path_file,
        study_label=args.study_label,
    )
    print("policy=", args.policy, flush=True)
    print("command=", " ".join(invocation), flush=True)
    if args.print_command:
        return
    completed = subprocess.run(invocation, cwd=root, check=False)
    raise SystemExit(completed.returncode)


if __name__ == "__main__":
    main()
